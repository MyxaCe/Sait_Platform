#!/bin/sh
# Подстановка публичных адресов в собранный вывод ПРИ ЗАПУСКЕ (WEB-22, Р-220).
#
# ## Зачем
#
# Next впекает `NEXT_PUBLIC_*` в сборку. Пока адреса приходили аргументами
# сборки, образ знал домен — и неизменяемый тег переставал означать «эта
# ревизия кода»: он означал «эта ревизия И этот домен». Домен временный,
# его сменят, а пересобирать образ ради смены адреса значит потерять смысл
# тега.
#
# Теперь образ собирается с ПЛЕЙСХОЛДЕРАМИ и домена не знает вовсе.
# Настоящие адреса приходят окружением контейнера, подстановка идёт здесь,
# до старта сервера. Это то же, что делает терминал своим `config.js` через
# envsubst (ADR-023), только для собранного вывода, а не для статики.
#
# ## Почему отказ, а не умолчание
#
# Незаданный адрес — это запуск, который отдаст ссылки в никуда. Молча
# подставить `localhost` значило бы выпустить образ, уверенно ведущий
# посетителя на его собственную машину. Поэтому нет значения — нет старта,
# с названием переменной в сообщении.
#
# **Пустая строка считается отсутствием** (WEB-21): именно пустой аргумент
# сборки однажды перекрыл умолчание и дал нерабочие кнопки входа.
set -eu

# Обход ограничен собранным выводом приложения. Весь `/app` — это ещё и
# `node_modules` на сотню мегабайт, где плейсхолдеров нет и быть не может;
# первая редакция обходила его по два раза на каждый адрес, и контейнер
# молчал минутами, прежде чем стартовать.
ROOT="${RUNTIME_CONFIG_ROOT:-/app/apps}"

# Список файлов-кандидатов считается ОДИН раз: текстовые файлы сборки,
# без `node_modules`.
CANDIDATES="$(find "$ROOT" -type d -name node_modules -prune -o -type f   \( -name '*.js' -o -name '*.html' -o -name '*.json' -o -name '*.css' -o -name '*.txt' \)   -print 2>/dev/null)"

# «плейсхолдер|переменная|обязательность». Добавить адрес — добавить строку.
#
# Плейсхолдер обязан быть СИНТАКСИЧЕСКИ ВЕРНЫМ адресом: сборка разбирает
# эти значения (`new URL(...)` в метаданных страниц) и падает на строке
# вроде `__RUNTIME_SITE_URL__` с «Invalid URL». Домен `.invalid`
# зарезервирован стандартом и не разрешается никогда — если подстановка
# не сработает, отказ будет громким, а не тихим уходом в чужой адрес.
#
# `optional` — не послабление, а состояние предметной области: пустой
# адрес фида означает «живого источника нет, работает мок», и это
# законный режим (так устроен и локальный стенд). Требовать его значило
# бы запретить запуск без MDS. Обязательные же без адреса дают ссылки в
# никуда, и там отказ — единственный честный исход.
# Разделитель — «|», а не «:»: двоеточие есть в самой схеме адреса.
PAIRS="https://runtime-site-url.invalid|NEXT_PUBLIC_SITE_URL|required
https://runtime-cabinet-url.invalid|NEXT_PUBLIC_CABINET_URL|required
https://runtime-terminal-url.invalid|NEXT_PUBLIC_TERMINAL_URL|required
https://runtime-ws-url.invalid|NEXT_PUBLIC_WS_URL|optional"

printf '%s\n' "$PAIRS" | while IFS='|' read -r placeholder var need; do
  [ -z "$placeholder" ] && continue

  # Плейсхолдера в сборке нет — значит этот адрес ей не нужен. Не требуем
  # переменную ради переменной: требование, которое нечем объяснить,
  # обходят первым.
  files="$(printf '%s
' "$CANDIDATES" | xargs -r grep -l "$placeholder" 2>/dev/null || true)"
  [ -z "$files" ] && continue

  raw="$(eval printf '%s' "\${$var:-}")"
  value="$(printf '%s' "$raw" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"

  if [ -z "$value" ] && [ "$need" = required ]; then
    echo "[runtime-config] $var не задана, а сборка её ждёт ($placeholder)." >&2
    echo "[runtime-config] Образ не знает домена сознательно (Р-220): адрес приходит" >&2
    echo "[runtime-config] окружением. Без него ссылки вели бы в никуда." >&2
    exit 1
  fi

  printf '%s\n' "$files" | while IFS= read -r file; do
    [ -n "$file" ] && sed -i "s|$placeholder|$value|g" "$file"
  done
  if [ -z "$value" ]; then
    echo "[runtime-config] $var пуста — подставляем пустое: режим без неё законен"
  else
    echo "[runtime-config] $var -> $value"
  fi
done

exec "$@"
