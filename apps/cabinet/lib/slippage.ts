/**
 * Проскальзывание: назвать человеку разницу между уровнем, который он
 * поставил, и ценой, по которой сделка исполнилась (WEB-20, Р-178).
 *
 * **Зачем вообще.** Владелец решил закрывать по первой наблюдённой цене, а
 * не по уровню триггера. Гарантия уровня означала бы, что разницу платит
 * брокер — на каждом скачке и без предела. Следствие для человека: закрытие
 * бывает **хуже поставленного уровня**, и без объяснения это читается как
 * наша ошибка. Убыток теперь ограничен не уровнем, а величиной разрыва
 * (Р-183) — тем более обязан быть назван.
 *
 * **Почему не всегда «хуже».** У лимитного ордера исполнение по рынку
 * всегда **не хуже** уровня, и разрыв играет ЗА клиента. Это то же правило,
 * а не исключение, поэтому направление считается, а не предполагается:
 * формулировка «проскальзывание» без знака молча превратила бы выигрыш в
 * оправдание.
 *
 * **Здесь только решение, без текстов** (ADR-012): наружу уходит машинный
 * ключ и величина, слова подставляет приложение.
 */

export type SlippageKind =
  /**
   * Уровня у нас нет — сказать нечего.
   *
   * Два случая под одним ключом **сознательно**: закрытие было не по
   * уровню (рыночное, по команде, неттинг) либо сделка закрыта до
   * появления поля. В обоих мы не знаем уровня и не вправе ни утверждать
   * «исполнено ровно», ни называть проскальзывание. Различить их в ПОКАЗЕ
   * нечем — разными они станут, только если источник начнёт присылать
   * «уровня не было» отдельно от «не знаю».
   */
  | 'unknown'
  /** Исполнение совпало с уровнем на видимой человеку точности. */
  | 'none'
  /** Исполнение хуже уровня: это и есть то, что нужно объяснить. */
  | 'against'
  /** Исполнение лучше уровня: разрыв сыграл за клиента. */
  | 'favour';

export interface SlippageVerdict {
  kind: SlippageKind;
  /** Модуль разницы в единицах цены; `0` при `none` и `unknown`. */
  amount: number;
}

export interface SlippageInput {
  /** Цена, по которой реально прошли деньги. */
  execution: number;
  /**
   * Уровень, который ставил человек.
   *
   * Пустое — уровня у нас НЕТ. Подставить сюда цену исполнения значило бы
   * получить «исполнено ровно по уровню» на сделке, про которую мы не
   * знаем ничего: то же умолчание, что `changePercent ?? 0`, только вывод
   * из него ещё и оправдывает нас (Р-118).
   */
  level: number | null | undefined;
  /**
   * Сторона **ПОЗИЦИИ**, которую человек держал, а не исполняемой ноги
   * (КОНТРАКТЫ.md §5, WEB-40).
   *
   * При закрытии длинной по проводу едет `buy`, хотя исполняется
   * продажа. Это решение терминала, не упущение: событие описывает
   * сделку, которую человек **держал**, и обратное отображение
   * показало бы в ленте сторону, противоположную той, что он видел в
   * терминале.
   *
   * Я прочитал это поле как сторону исполнения — и знак вердикта
   * переворачивался. Разбор ниже.
   */
  side: 'buy' | 'sell';
  /** Знаков после запятой у инструмента — та точность, которую человек видит. */
  digits: number;
}

/**
 * Вердикт по одной сделке.
 *
 * **Сравнение идёт на видимой точности, а не на сырых числах.** Разницу,
 * которой не видно на экране, называть нельзя: человек прочитает «есть
 * проскальзывание» и не найдёт его глазами. Это тот же принцип, по которому
 * мы не показываем «0.00%» вместо отсутствующего значения — сообщение
 * обязано соответствовать тому, что видно.
 *
 * **Направление зависит от стороны, и перепутать его легко — я и
 * перепутал.** `side` называет сторону ПОЗИЦИИ: для длинной (`buy`)
 * хуже — ниже уровня, для короткой (`sell`) хуже — выше. Закреплено
 * тестами с обеих сторон и названо в каждом из них словами «была
 * длинная»/«была короткая», а не «buy»/«sell»: прежние имена читались
 * как сторона исполнения и уводили ровно туда, куда увели.
 */
export function describeSlippage({
  execution,
  level,
  side,
  digits,
}: SlippageInput): SlippageVerdict {
  // Проверка стоит ДО арифметики: любое сравнение ниже превратило бы
  // «не знаем уровня» в утверждение о нём.
  if (level === null || level === undefined) return { kind: 'unknown', amount: 0 };

  const factor = 10 ** digits;
  const shown = (value: number) => Math.round(value * factor) / factor;

  const exec = shown(execution);
  const target = shown(level);

  if (exec === target) return { kind: 'none', amount: 0 };

  /*
    `buy` — была ДЛИННАЯ: закрывается продажей, и хуже — дешевле уровня.
    `sell` — была КОРОТКАЯ: закрывается покупкой, и хуже — дороже.

    Здесь стояло обратное: я прочитал `side` как сторону исполняемой
    ноги. На любых данных это даёт ответ, и ответ уверенный, —
    поэтому ни один тест не краснел: мои собственные примеры были
    построены по тому же неверному прочтению, и правило с проверкой
    ошибались согласованно.

    Цена ошибки несимметрична. Молчание было бы потерей; здесь же
    стоп, исполнившийся хуже уровня, говорил человеку «в вашу пользу».
    Это не отсутствие объяснения, а бодрое неверное.
  */
  const worse = side === 'buy' ? exec < target : exec > target;

  return {
    kind: worse ? 'against' : 'favour',
    amount: shown(Math.abs(exec - target)),
  };
}
