import type { Quote } from '@broker/realtime';

/** Котировка, про которую точно известно, на сколько она изменилась. */
type QuoteWithChange = Quote & { changePercent: number };

/**
 * Кто попадает во вкладку «Лидеры роста» и в каком порядке.
 *
 * Вынесено из `MarketsModule.tsx` отдельным модулем по той же причине, что и
 * `describeNotice`: это чистая функция и единственное место, где решается
 * «кого считать лидером роста». Внутри `'use client'`-компонента проверить её
 * можно было бы только через браузерный харнесс, а дорогую проверку перестают
 * запускать.
 *
 * Правило про пустое изменение (КОНТРАКТЫ.md, Р-118): инструмент с
 * неизвестным изменением **не лидер роста**. Показать его здесь значило бы
 * утверждать, что он растёт, — а мы этого не знаем.
 *
 * Условие названо явно, а не оставлено на то, что `null > 0` ложно. Исход
 * совпадает, но на молчаливую ветку по умолчанию опираться нельзя: именно так
 * пустое значение и утекает незамеченным. Предикат заодно сужает тип, и до
 * вычитания в компараторе `null` не доходит — `null - null` дало бы `NaN`, а
 * компаратор, вернувший `NaN`, рвёт порядок молча и невоспроизводимо.
 */
export function selectGainers(quotes: readonly Quote[]): QuoteWithChange[] {
  return quotes
    .filter((q): q is QuoteWithChange => q.changePercent !== null && q.changePercent > 0)
    .sort((a, b) => b.changePercent - a.changePercent);
}
