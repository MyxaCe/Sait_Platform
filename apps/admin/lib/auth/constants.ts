/**
 * Общие константы операторского auth. Импортируются и в middleware (edge),
 * поэтому здесь не должно быть node-зависимостей — только значения.
 */

/**
 * Кука операторской сессии. ОТДЕЛЬНАЯ от клиентской `cabinet_session` (Р-395):
 * вход в управление и вход в кабинет нельзя спутать одной кукой. Имя, область
 * и механизм разные — операторская сессия не неотличима от клиентской.
 */
export const ADMIN_SESSION_COOKIE = 'admin_operator_session';

/**
 * Промежуточные httpOnly-куки двух шагов TOTP (ADM-13, Р-454). ОТДЕЛЬНЫЕ от
 * сессионной: несут не доступ, а состояние незавершённого входа/регистрации.
 *  - CHALLENGE: «пароль проверен, жду второй фактор» (5 мин).
 *  - ENROLL: непроверенный секрет на время регистрации (10 мин).
 * Значения — только имена кук; node-зависимостей здесь нет (edge-safe).
 */
export const ADMIN_TOTP_CHALLENGE_COOKIE = 'admin_totp_challenge';
export const ADMIN_TOTP_ENROLL_COOKIE = 'admin_totp_enroll';

/** Публичные СТРАНИЦЫ поверхности: всё остальное закрыто гейтом (Р-394). */
export const PUBLIC_PATHS = ['/login'] as const;

/**
 * ЯВНЫЙ allowlist публичных `/api`-роутов (Р-451).
 *
 * `/api` закрыт по умолчанию (default-deny в middleware). Исключение — только
 * то, что здесь названо, и у каждого исключения своя причина быть публичным:
 *
 *  - `/api/health` — liveness-проба оркестратора/балансировщика, до и без
 *    всякой сессии; секретов не отдаёт (только «готов ли гейт закрываться»).
 *  - `/api/platform-transfer/v1/messages` — приём межплатформенных сообщений
 *    перевода клиента (ветка client-transfer). Операторской сессии у соседней
 *    платформы нет и быть не может: своя проверка — подпись Ed25519 ключом из
 *    реестра группы, одноразовый nonce, окно времени ±5 мин. Ходят сюда по
 *    внутренней сети ячеек (back), снаружи путь закрыт IP-фильтром админки.
 *
 * Новый публичный роут обязан появиться ЗДЕСЬ явно И иметь собственную
 * проверку (defense in depth: middleware не последний рубеж). Роут, которого
 * тут нет, middleware закрывает — 401 без сессии. Тест `/api` default-deny
 * ходит по ВСЕМ роутам и ловит добавленный мимо этого списка.
 */
export const API_PUBLIC_PATHS = ['/api/health', '/api/platform-transfer/v1/messages'] as const;

/** Куда гейт отправляет запрос без валидной операторской сессии. */
export const LOGIN_PATH = '/login';
