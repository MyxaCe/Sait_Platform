/**
 * Видно ли содержимое посетителю из такой-то юрисдикции (Р-045, Р-058).
 *
 * **Почему это вообще у нас, а не импортируется.** Правило обязано быть
 * одним на всех потребителей: витрину, кабинет, терминал и предпросмотр
 * CMS. Один модуль на всех физически невозможен — терминал написан на
 * Rust и TypeScript взять не может. Поэтому контрактом стала **таблица
 * эталонных случаев** (`contracts/visibility-cases.v1.json`), и каждая
 * реализация прогоняет её своим тестом; расхождение становится красным
 * тестом у того, кто разошёлся, а не жалобой из регулируемой
 * юрисдикции.
 *
 * **Честная граница, и её надо держать на виду.** Прохождение таблицы
 * доказывает **согласие с прочтением CMS**, а не правильность
 * прочтения. Таблицу писал автор правила; если он понял юрисдикции
 * неверно, все реализации ошибутся одинаково и согласованно. Против
 * этого таблица не защищает и защищать не может — это задача того, кто
 * утверждает список юрисдикций.
 *
 * **Выдача не фильтрует.** `bootstrap.navigation[].jurisdictions`
 * приезжает как есть, решение принимает потребитель. Поэтому решение
 * живёт здесь, а не размазано по компонентам: правило в регуляторной
 * области, у которого нет одного места, расходится само собой.
 *
 * ## Три умолчания, и все три несимметричны
 *
 *  1. **Ограничения нет → видно во всех.** Запрет задаётся явно.
 *     Обратное умолчание прятало бы содержимое молча, и заметить это
 *     было бы некому.
 *  2. **Мусор вместо ограничения → видно.** Негодная форма поля это
 *     отсутствие ограничения, а не ограничение, которое мы не поняли:
 *     потребитель парсит мягко (КОНТРАКТЫ.md). Иначе опечатка в CMS
 *     тихо гасила бы раздел.
 *  3. **Ограничение есть, юрисдикция посетителя неизвестна → НЕ
 *     видно.** «Я не знаю, где вы» не является доказательством, что
 *     показывать можно. Лишний раз скрытый блок чинят, показанный не
 *     там — объясняют регулятору.
 *
 * Третье умолчание направлено противоположно первым двум, и это не
 * непоследовательность: первые два про **намерение редактора**, третье
 * про **знание о посетителе**.
 */

/**
 * КАКОЙ барьер принял решение. Поле машинное и отдельное от `reason`.
 *
 * Заведено не для красоты, а потому что без него один из барьеров
 * оказался непроверяемым. Мутация «снять ветку „юрисдикция посетителя
 * не задана“» **не покрасила ни одного теста**, включая все 14
 * эталонных случаев: ограничение `['uk-fca']` при `jurisdiction: null`
 * и так не проходит через `list.includes(null)`, то есть отказ
 * обеспечивает СОСЕДНИЙ слой. Видимый исход совпадает до буквы, а
 * охраняемое свойство — нет.
 *
 * Это дословно история с подменой `alg`: три зелёных теста держались на
 * защите внутри библиотеки, и снятие собственной проверки их не
 * покрасило. Эшелонированная защита делает тесты зелёными по неверной
 * причине, и отличить умеет только наблюдаемое различие.
 *
 * Разница существенна не только для тестов. `visitor-unknown` означает
 * «мы не знаем посетителя» — это чинится определением юрисдикции;
 * `other-jurisdiction` означает «знаем, и ему нельзя» — это не чинится
 * вовсе. Один исход, два разных диагноза.
 */
export type VisibilityReason =
  /** Ограничение есть, а юрисдикция посетителя неизвестна (не задана
   *  либо пустая строка). Чинится знанием о посетителе. */
  | 'jurisdiction-unknown'
  /** Юрисдикция известна, и в списке ограничений её нет. Чинится
   *  составом списка. */
  | 'jurisdiction-not-listed';

export interface VisibilityVerdict {
  readonly visible: boolean;
  /**
   * МАШИННЫЙ код отказа, как его называет контракт. `null` — видно.
   *
   * Отдельно от подписи сознательно и теперь ещё и по контракту:
   * «код отказа и подпись для человека — два разных поля», и признак,
   * по которому проверка отличает состояния, не должен ходить через
   * перевод. У нас это уже было багом: в `data-access-reason` однажды
   * легла переведённая строка.
   */
  readonly reason: VisibilityReason | null;
  /**
   * Подпись для человека. Не контракт — её можно и нужно переводить.
   *
   * Имя поля согласовано с остальными реализациями (штаб, 19.10):
   * машинный код зовётся `reason`, человеческая строка — `explanation`.
   * Один словарь на три реализации дешевле трёх похожих.
   */
  readonly explanation: string | null;
}

/**
 * Приводит поле ограничений к списку кодов.
 *
 * Формы записи две: плоский список строк и повторяемая группа
 * `[{ code }]`. Читает их ОДНА функция намеренно — двое читающих
 * разошлись бы в мелочах (пробелы, пустые строки, чужая форма), и
 * разошлись бы молча: ограничение, прочитанное как пустое, означает
 * «видно всем».
 */
export function readJurisdictions(value: unknown): string[] {
  if (!Array.isArray(value)) return [];

  return value.flatMap((entry) => {
    if (typeof entry === 'string' && entry.trim() !== '') return [entry.trim()];

    if (entry !== null && typeof entry === 'object' && 'code' in entry) {
      const code = (entry as { code: unknown }).code;
      return typeof code === 'string' && code.trim() !== '' ? [code.trim()] : [];
    }

    return [];
  });
}

export function visibilityIn(
  restrictions: unknown,
  jurisdiction: string | null,
): VisibilityVerdict {
  const list = readJurisdictions(restrictions);

  if (list.length === 0) return { visible: true, reason: null, explanation: null };

  // Пустая строка — та же незаданность, а не особая юрисдикция.
  if (jurisdiction === null || jurisdiction === '') {
    return {
      visible: false,
      reason: 'jurisdiction-unknown',
      explanation: `Ограничено юрисдикциями (${list.join(', ')}), а юрисдикция не задана: неизвестность не разрешение.`,
    };
  }

  // Сравнение посимвольное и регистрозависимое. Приведение регистра
  // пришлось бы повторять в каждой реализации, и первая же, которая его
  // забудет, разойдётся с остальными молча.
  if (list.includes(jurisdiction)) return { visible: true, reason: null, explanation: null };

  return {
    visible: false,
    reason: 'jurisdiction-not-listed',
    explanation: `Ограничено юрисдикциями (${list.join(', ')}) — в «${jurisdiction}» не показывается.`,
  };
}

/** Пункт меню и его потомки. Форма повторяет `NavItemResponse` контракта. */
export interface NavVisibilityNode {
  readonly jurisdictions?: unknown;
  readonly children?: unknown;
}

export interface NavFilterResult<TItem> {
  readonly items: TItem[];
  /** Сколько пунктов скрыто ВМЕСТЕ с подпунктами. */
  readonly hidden: number;
}

/**
 * Прячет из меню то, что в этой юрисдикции не показывается.
 *
 * Скрытый пункт уходит **вместе с подпунктами**: раздела, которого нет,
 * не бывает с видимыми подпунктами — витрина нарисовала бы подпункты без
 * заголовка.
 *
 * Число скрытого возвращается **отдельно и всегда**. Пустое меню и меню,
 * из которого всё убрала юрисдикция, выглядят одинаково, а означают
 * разное: без этого числа «нечего показывать» неотличимо от «всё
 * спрятано», и регуляторный фильтр, сработавший слишком широко, не
 * оставляет следа нигде.
 */
export function filterNavByJurisdiction<TItem extends NavVisibilityNode>(
  items: readonly TItem[],
  jurisdiction: string | null,
): NavFilterResult<TItem> {
  // Поле приходит из JSON: «не список» — это пустое меню, а не исключение.
  if (!Array.isArray(items)) return { items: [], hidden: 0 };

  const kept: TItem[] = [];
  let hidden = 0;

  for (const item of items) {
    if (item === null || typeof item !== 'object') continue;

    if (!visibilityIn(item.jurisdictions, jurisdiction).visible) {
      hidden += 1;
      continue;
    }

    const below = filterNavByJurisdiction((item.children ?? []) as readonly TItem[], jurisdiction);
    hidden += below.hidden;

    kept.push({ ...item, children: below.items });
  }

  return { items: kept, hidden };
}
