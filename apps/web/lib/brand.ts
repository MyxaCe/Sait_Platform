/**
 * Фирменный цвет витрины.
 *
 * `hexToRgbChannels` переехал в `@broker/utils` (общий хром сайта и
 * кабинета, ADR-025) и ре-экспортируется отсюда.
 *
 * **Запасной цвет — наш, и он назван здесь** (WEB-05, решение штаба
 * Р-040). В legacy `brand.primaryColor` всегда строка с умолчанием, в
 * CMS v2 это `string | null`: `null` значит «не задан». Без
 * собственного запасного значения переезд контура на v2 дал бы страницу
 * без фирменного цвета — незаметно и на всех 153 страницах сразу.
 *
 * Почему не «просто не инжектировать переменную и положиться на токен».
 * Так было раньше, и это работало ПРАВИЛЬНО СЛУЧАЙНО: цвет держался на
 * том, что в `@broker/ui/tokens.css` у `--accent` оказалось то же
 * значение. Любая правка токенов меняла бы фирменный цвет витрины
 * молча, и ни один тест бы не покраснел. Теперь это решение, а не
 * побочное свойство: значение названо, у него есть источник и тест.
 */

export { hexToRgbChannels } from '@broker/utils';

/**
 * Запасной фирменный цвет витрины. Совпадает с `--accent` тёмной темы в
 * токенах `@broker/ui` — намеренно: подмена не должна быть заметна
 * посетителю. Совпадение закреплено тестом, иначе оно разъедется.
 */
export const FALLBACK_PRIMARY_COLOR = '#d4a437';

/** Откуда взят цвет. Нужен в тесте и в отладке: «цвет есть» и «цвет от
 *  источника» — разные утверждения, и первое не доказывает второго. */
export type PrimaryColorSource = 'cms' | 'fallback';

export interface ResolvedPrimaryColor {
  readonly color: string;
  readonly source: PrimaryColorSource;
}

/**
 * Какой фирменный цвет показать. `null` и пустая строка от источника —
 * «не задан», а не «чёрный»: подставлять правдоподобное значение вместо
 * отсутствующего мы перестали везде, и цвет не исключение.
 */
export function resolvePrimaryColor(fromCms: string | null | undefined): ResolvedPrimaryColor {
  return fromCms
    ? { color: fromCms, source: 'cms' }
    : { color: FALLBACK_PRIMARY_COLOR, source: 'fallback' };
}
