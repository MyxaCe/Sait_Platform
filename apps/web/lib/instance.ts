import os from 'node:os';

/**
 * Кто именно отвечает на health-пробу (баг B-019).
 *
 * Поле `service: "site-web"` называет ПРИЛОЖЕНИЕ, а не экземпляр. На одной
 * машине спокойно живут два экземпляра одного приложения с разной
 * конфигурацией — локальный и контурный в Docker, — и по ответу они
 * неотличимы. Проверка «что будет без переменной» из-за этого едва не
 * подтвердилась на экземпляре, где переменные заданы.
 *
 * Признаки ниже подобраны так, чтобы экземпляр НЕ выбирал их себе сам:
 * самоназвание — ровно то, что подвело. `hostname` в контейнере это его id,
 * на хосте — имя машины; `pid` различает два процесса на одной машине.
 */
export interface InstanceIdentity {
  /** Контейнер → его id, хост → имя машины. Назначается снаружи процесса. */
  host: string;
  /** Различает два процесса одного приложения на одной машине. */
  pid: number;
  /**
   * Момент старта процесса. Считается из `process.uptime()` НА КАЖДЫЙ запрос,
   * а не запоминается в модуле: значение, вычисленное на этапе сборки,
   * замерзает в образе и начинает врать (урок B-010).
   */
  startedAt: string;
}

export function instanceIdentity(): InstanceIdentity {
  return {
    host: os.hostname(),
    pid: process.pid,
    startedAt: new Date(Date.now() - process.uptime() * 1000).toISOString(),
  };
}

/**
 * Рантаймовые переменные, от которых зависит поведение сайта — машинная
 * версия таблицы «переменная не задана → что будет» из
 * docs/Локальный запуск.md.
 *
 * Сознательно НЕ включён `FRAME_ANCESTORS`: он читается на СБОРКЕ и
 * запекается в заголовок, а в готовом образе `process.env` его уже не
 * содержит. Отпечаток сказал бы «не задано» о значении, которое на самом
 * деле действует, — а поле, способное соврать, здесь хуже отсутствующего.
 * `BUILD_STANDALONE` — по той же причине; `SENTRY_ENV` — косметика;
 * `CABINET_URL`/`TERMINAL_URL`/`MDS_E2E` — только e2e.
 *
 * Про `NEXT_PUBLIC_*` читать точно: отпечаток отражает взгляд СЕРВЕРА в
 * рантайме. Клиентский бандл несёт значение, вшитое на сборке, и эти два
 * могут расходиться. Серверный код (`lib/mds.ts`) читает именно рантайм,
 * поэтому поле не бесполезно — но оно отвечает на вопрос про сервер.
 */
const TRACKED_ENV = [
  'DATABASE_URL',
  'CMS_API_URL',
  'CMS_API_KEY',
  'CMS_WEBHOOK_SECRET',
  'PREVIEW_SECRET',
  'MDS_HTTP_URL',
  'NEXT_PUBLIC_WS_URL',
  'NEXT_PUBLIC_SITE_URL',
  'NEXT_PUBLIC_CABINET_URL',
  'SITE_SLUG',
  'SENTRY_DSN',
  'NEXT_PUBLIC_SENTRY_DSN',
  'ALLOW_SENTRY_TEST',
] as const;

/**
 * Отпечаток конфигурации: КАКИЕ переменные заданы, но НЕ что в них лежит.
 * Только булевы значения — ручка не должна становиться местом утечки, а
 * сами имена уже опубликованы в `.env.example`, нового они не сообщают.
 */
export function configFingerprint(): Record<string, boolean> {
  const out: Record<string, boolean> = {};
  for (const name of TRACKED_ENV) {
    const value = process.env[name];
    // Пустая строка — это «не задано»: `CMS_API_URL=` в .env ведёт себя
    // как отсутствие, и отпечаток обязан говорить то же самое.
    out[name] = typeof value === 'string' && value.length > 0;
  }
  return out;
}
