import os from 'node:os';

/**
 * Кто именно отвечает на health-пробу (баг B-019).
 *
 * Поле `service: "site-web"` называет ПРИЛОЖЕНИЕ, а не экземпляр. На одной
 * машине спокойно живут два экземпляра одного приложения с разной
 * конфигурацией — локальный и контурный в Docker, — и по ответу они
 * неотличимы. Проверка «что будет без переменной» из-за этого едва не
 * подтвердилась на экземпляре, где переменные заданы.
 *
 * Признаки ниже подобраны так, чтобы экземпляр НЕ выбирал их себе сам:
 * самоназвание — ровно то, что подвело. `hostname` в контейнере это его id,
 * на хосте — имя машины; `pid` различает два процесса на одной машине.
 */
export interface InstanceIdentity {
  /** Контейнер → его id, хост → имя машины. Назначается снаружи процесса. */
  host: string;
  /** Различает два процесса одного приложения на одной машине. */
  pid: number;
  /**
   * Момент старта процесса. Считается из `process.uptime()` НА КАЖДЫЙ запрос,
   * а не запоминается в модуле: значение, вычисленное на этапе сборки,
   * замерзает в образе и начинает врать (урок B-010).
   */
  startedAt: string;
}

export function instanceIdentity(): InstanceIdentity {
  return {
    host: os.hostname(),
    pid: process.pid,
    startedAt: new Date(Date.now() - process.uptime() * 1000).toISOString(),
  };
}

/**
 * Переменные, которые читает САМ ПРОЦЕСС в рантайме — машинная версия
 * таблицы «переменная не задана → что будет» из
 * docs/Локальный запуск.md.
 *
 * **Что это поле измеряет (WEB-09, B-030).** Ровно одно: что лежит в
 * `process.env` отвечающего процесса СЕЙЧАС. Поэтому здесь нет ни одной
 * переменной, действующей по природе сборки: про такую отпечаток сказал
 * бы «не задано» о значении, которое действует. Их снимок берётся на
 * сборке и живёт в `buildFingerprint()` ниже.
 *
 * Разделение не косметика. Чтение здесь **динамическое** —
 * `process.env[name]` по имени из списка, — и ни один компилятор
 * динамический доступ не инлайнит. То есть этот список **структурно
 * неспособен** увидеть сборочное значение, сколько его сюда ни клади.
 * Поле, способное соврать, хуже отсутствующего — тот же критерий, по
 * которому отсюда убрали `FRAME_ANCESTORS`.
 *
 * `NEXT_PUBLIC_WS_URL` остался СОЗНАТЕЛЬНО и стоит в обоих отпечатках:
 * сервер читает его в рантайме (`lib/mds.ts`, иконки), браузер — из
 * бандла. Два значения могут разойтись, и это тот случай, когда
 * расхождение видеть важнее всего: подлинность котировок
 * (`live` против `simulated`) решается в браузере по СБОРОЧНОМУ
 * значению, а не по этому.
 *
 * Вне обоих списков: `SENTRY_ENV` — косметика;
 * `CABINET_URL`/`TERMINAL_URL`/`MDS_E2E` — только e2e.
 */
const TRACKED_ENV = [
  'DATABASE_URL',
  'CMS_API_URL',
  'CMS_API_KEY',
  'CMS_WEBHOOK_SECRET',
  'PREVIEW_SECRET',
  'MDS_HTTP_URL',
  'NEXT_PUBLIC_WS_URL',
  'SITE_SLUG',
  'SENTRY_DSN',
  'ALLOW_SENTRY_TEST',
] as const;

/**
 * Отпечаток конфигурации: КАКИЕ переменные заданы, но НЕ что в них лежит.
 * Только булевы значения — ручка не должна становиться местом утечки, а
 * сами имена уже опубликованы в `.env.example`, нового они не сообщают.
 */
export function configFingerprint(): Record<string, boolean> {
  const out: Record<string, boolean> = {};
  for (const name of TRACKED_ENV) {
    const value = process.env[name];
    // Пустая строка — это «не задано»: `CMS_API_URL=` в .env ведёт себя
    // как отсутствие, и отпечаток обязан говорить то же самое.
    out[name] = typeof value === 'string' && value.length > 0;
  }
  return out;
}

/**
 * Отпечаток СБОРОЧНЫХ переменных: что было задано в момент `next build`.
 *
 * Снимок делает `next.config.mjs` и кладёт в `BUILD_CONFIG_FINGERPRINT`
 * через `env`, то есть компилятор впекает его в бандл. Читается он
 * статическим обращением к `process.env.BUILD_CONFIG_FINGERPRINT` —
 * именно статическим, иначе инлайна не будет и мы получим `undefined` в
 * образе, то есть ту же ложь с другой стороны.
 *
 * **Это значение замерзает в образе, и здесь это правильно.** Правило
 * B-010 запрещает замораживать то, что описывает рантайм — момент старта
 * процесса. Здесь описывается сама сборка; замороженный снимок —
 * единственная честная её форма, и пересчитывать его на запрос не из
 * чего.
 *
 * Снимка нет — отдаём `null`, а не пустой объект: «собрано без снимка»
 * (старый образ) и «на сборке ничего не было задано» — разные факты, и
 * пустой объект выдал бы первое за второе.
 */
export function buildFingerprint(): Record<string, boolean> | null {
  const raw = process.env.BUILD_CONFIG_FINGERPRINT;
  if (typeof raw !== 'string' || raw.length === 0) return null;
  try {
    const parsed: unknown = JSON.parse(raw);
    if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) return null;
    const out: Record<string, boolean> = {};
    for (const [name, value] of Object.entries(parsed as Record<string, unknown>)) {
      // Снимок наш собственный, но разбор всё равно строгий: непонятое
      // значение не имеет права стать `false`, то есть «не задано».
      if (typeof value !== 'boolean') return null;
      out[name] = value;
    }
    return out;
  } catch {
    return null;
  }
}
