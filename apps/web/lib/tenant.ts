/**
 * Доступ витрины к инструментам — allow-list с карточки сайта в CMS
 * (конфиг тенанта `GET {CMS_API_URL}/cms/sites/{slug}`).
 *
 * **Решение живёт в `@broker/tenant`, не здесь** (Р-029, PKG-04). Этот
 * файл — только адаптер: читает окружение витрины и задаёт её параметры
 * кеширования. Раньше тут лежала дословная копия решения, вторая копия —
 * в кабинете, и держать их в соответствии должны были парные тесты. Тип
 * убрал расхождение, возможность расхождения кода осталась — а Р-025
 * именно про неё.
 *
 * Что это за граница и почему она fail-closed — в шапке
 * `packages/tenant/src/access.ts`; срок годности списка — там же в
 * `expiry.ts` (Р-030).
 *
 * ## WEB-07: граница вычисляется В РАНТАЙМЕ, а не на сборке
 *
 * Fail-closed спасает разрешение, но не диагноз. После пересборки витрина
 * закрывала доступ ПРАВИЛЬНО и объясняла его НЕВЕРНО: вместо «инструменты
 * не выбраны» говорила «список недоступен, это сбой платформы» — и
 * отправляла чинить то, что не сломано.
 *
 * Причина: `CMS_API_URL` — рантаймовая переменная, на сборке её нет.
 * `fetchTenantConfig` без неё коротит в `not-configured`, страница
 * пререндерится с этим состоянием, и «не настроено» замерзает в готовой
 * разметке вместе со всем остальным. В образе лежал готовый HTML с
 * диагнозом сборки, а `/api/health` того же контейнера в тот же момент
 * показывал переменную заданной.
 *
 * Лечится `noStore()`: он помечает рендер как рантаймовый, и любой
 * сегмент, спросивший границу, считается динамическим. Почему именно он,
 * а не `cache: 'no-store'` на запросе: `no-store` отменил бы заодно
 * редакционное окно и инвалидацию вебхуком (Р-030, ADR-009) — то есть
 * чинил бы диагноз ценой свойства, к дефекту отношения не имеющего.
 * Запрос к CMS по-прежнему кешируется на `EDITORIAL_REUSE_WINDOW_SECONDS`
 * и по-прежнему сбрасывается тегами; заново на каждый запрос считается
 * только РЕШЕНИЕ, и считается из рантаймового окружения.
 *
 * **Статика при этом не отменена целиком.** `noStore()` выводит из
 * пререндера ровно те сегменты, которые спрашивают границу: страницы
 * инструментов (список и деталка). Остальная витрина — редакционная
 * граница (Р-030, п. 2) и собирается статически; строку тикера на всех
 * страницах считает рантаймовый островок
 * (`features/quotes/TickerGate.tsx` + `app/api/tenant/access`), потому
 * что иначе вопрос к границе в общем макете увёл бы в динамику все 156
 * страниц. Числа до и после — в `docs/Журнал багов.md#B-026`.
 */

import { unstable_noStore as noStore } from 'next/cache';
import {
  accessNotice,
  EDITORIAL_REUSE_WINDOW_SECONDS,
  fetchTenantConfig,
  isAccessClosed,
  isSymbolAllowed,
  type TenantAccess,
} from '@broker/tenant';

export { accessNotice, isAccessClosed, isSymbolAllowed };
export type {
  AccessNoticeSpec,
  TenantAccess,
  TenantAccessUnavailableReason,
} from '@broker/tenant';

export async function getTenantAccess(): Promise<TenantAccess> {
  /**
   * ПЕРВОЙ строкой и до чтения окружения (WEB-07). Значение, вычисленное
   * на сборке, замерзает в образе — а здесь замерзала не величина, а
   * ПРИЧИНА отказа, то есть указание, куда идти чинить.
   *
   * Вызов обязан стоять до любого `await`: `noStore()` действует на
   * сегмент, который сейчас рендерится, и после первого `await` рендер
   * может уже не быть нашим.
   */
  noStore();

  const slug = process.env.SITE_SLUG ?? 'apex-ru';
  const { access } = await fetchTenantConfig({
    baseUrl: process.env.CMS_API_URL,
    slug,
    apiKey: process.env.CMS_API_KEY || undefined,
    /**
     * Редакционное окно витрины (ADR-009) плюс инвалидация вебхуком
     * карточки сайта. Это НЕ срок годности списка: срок приходит от
     * источника, и когда он короче окна, границу закрывает он
     * (`applyListExpiry` внутри пакета), а не эта цифра.
     *
     * Окно переживает WEB-07 намеренно: оно про переиспользование
     * ОТВЕТА CMS, а замерзало — РЕШЕНИЕ о доступе. Разные вещи, и
     * чинится только вторая.
     */
    fetchInit: {
      next: {
        revalidate: EDITORIAL_REUSE_WINDOW_SECONDS,
        tags: ['cms:brand', `cms:brand:${slug}`],
      },
    } as RequestInit,
  });
  return access;
}
