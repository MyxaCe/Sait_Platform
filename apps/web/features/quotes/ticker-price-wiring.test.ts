import { readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * PKG-06 · проводка общего правила про цену (Р-070, Р-127).
 *
 * Само правило закреплено поведением в `@broker/realtime` (`displayPrice`).
 * Здесь проверяется другое: что витрина его ЗОВЁТ. Мутация «вернуть
 * `formatPrice` прямо в элемент» не красит ни один поведенческий тест —
 * лента рисуется, цена есть, просто зашитая базовая цена справочника
 * показывается погашенной и подписанной «последняя известная». Это хуже
 * прочерка: утверждение «цена такая была», которого не было.
 *
 * Класс «функция исправна, но её не зовут» модульным тестом не ловится в
 * принципе — тот же урок, что у каталога (WEB-08).
 */

const TICKER = path.resolve(__dirname, 'QuotesTicker.tsx');

/**
 * Код без комментариев: моя же проза называет `displayPrice` по имени, и
 * проверка по сырому тексту осталась бы зелёной после того, как вызов
 * убрали, а объяснение забыли стереть.
 */
const code = readFileSync(TICKER, 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/(^|[^:])\/\/.*$/gm, '$1');

describe('QuotesTicker · цена берётся общим правилом', () => {
  it('зовёт displayPrice, а не форматирует цену сам', () => {
    expect(code).toMatch(/price:\s*displayPrice\(/);
  });

  it('не подставляет formatPrice прямо в элемент ленты', () => {
    // Именно эта запись и была до PKG-06.
    expect(code).not.toMatch(/price:\s*formatPrice\(/);
  });
});
