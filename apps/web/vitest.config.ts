import path from 'node:path';
import react from '@vitejs/plugin-react';
import { defineConfig } from 'vitest/config';
import { poolOptions } from '@broker/config/vitest-pool.js';

/**
 * WEB-16 · в витрине появляются компонентные проверки.
 *
 * **Чего не хватало.** Окружение было `node`, а в наборе только
 * `.test.ts` — файл `.tsx` не мог попасть в прогон, даже если бы его
 * написали. Следствие не в том, что «тестов мало»: **правка в разметке
 * не краснела ничем**. Логику каждый раз выносили в соседний `.ts`
 * модуль, чтобы было что проверить, а слой, который эту логику зовёт,
 * оставался непроверяемым — и класс «функция исправна, но её не зовут»
 * приходилось закрывать проверками по тексту программы.
 *
 * Текст — законная замена там, где у запрета **нет наблюдаемых
 * последствий**. Здесь они есть: не та цена видна в разметке. Текстовая
 * проверка стояла не потому, что следствие невидимо, а потому, что его
 * **нечем было увидеть**.
 *
 * **Два окружения в одном прогоне.** Узловые проверки остаются узловыми:
 * половина из них о том, что мы НЕ ходим в сеть, и подменять им
 * окружение на браузерное значило бы менять предмет проверки. Браузерное
 * включается только для `.test.tsx`.
 *
 * Уклад взят из `packages/ui`, где компонентные проверки уже живут: те
 * же версии, тот же плагин, то же `globals` ради авто-очистки RTL.
 * Второй уклад для того же дела был бы вторым источником одной нормы.
 *
 * **Набор файлов проверяется отдельно** (`harness.test.ts`): шаблон,
 * не совпавший ни с чем, даёт безупречно зелёный прогон, который не
 * смотрит никуда. Здесь это не теория — ровно так выглядело прежнее
 * состояние витрины.
 */
export default defineConfig({
  plugins: [react()],
  resolve: {
    alias: {
      '@': path.resolve(__dirname, '.'),
    },
  },
  test: {
    // Ограничение пула — общее для всех пакетов (WEB-37).
    poolOptions,
    environment: 'node',
    // RTL вешает авто-очистку на глобальный `afterEach`.
    globals: true,
    environmentMatchGlobs: [['**/*.test.tsx', 'jsdom']],
    include: [
      'features/**/*.test.ts',
      'lib/**/*.test.ts',
      'features/**/*.test.tsx',
      'components/**/*.test.tsx',
      'app/**/*.test.tsx',
    ],
  },
});
