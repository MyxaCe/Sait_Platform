import { test } from '@playwright/test';

/**
 * Пропуски сквозных проверок: один уклад на все (WEB-30).
 *
 * **Чем опасен пропуск.** Пропущенная проверка в сводке выглядит почти
 * как пройденная: прогон зелёный, строка есть, цвет спокойный. Пока
 * возможности нет — это честно. Но в прогоне, который **должен был**
 * её покрыть, пропуск неотличим от успеха, и покрытие существует
 * только на словах.
 *
 * **Чему научил первый такой гейт.** Он требовал отказа «в CI» — и
 * покрасил основную ветку на три дня. Утверждение было неверным:
 * обычный прогон поднимает одну витрину, и кабинета с терминалом в
 * нём быть не может. **Гейт, который невозможно удовлетворить,
 * отключают.** Поэтому прогон объявляет себя сам: переменную ставит
 * тот, кто поднял нужную сторону.
 *
 * **Два разных пропуска, и они названы по-разному нарочно.**
 * `requireOrSkip` — возможности нет (не поднят сосед, нет живой CMS).
 * `skipAsOtherScenario` — возможность есть, но этот файл проверяет
 * противоположное состояние. Второй никогда не станет обязательным, и
 * путать их нельзя: первый это долг, второй — развилка.
 */

/**
 * Пропустить, пока возможности нет, — и ОТКАЗАТЬ, если прогон объявил
 * себя обязанным её покрыть.
 *
 * @param required имя переменной, которой прогон объявляет: «я обязан».
 */
export function requireOrSkip(options: {
  /** Возможности нет: сосед не поднят, окружение не задано. */
  gated: boolean;
  /** Имя переменной вида `*_E2E_REQUIRED`. */
  required: string;
  /** Что именно остаётся непроверенным. Уходит в текст отказа. */
  what: string;
  /** Чего не хватает — по этому дежурный поймёт, что поднять. */
  missing: string;
}): void {
  const mustRun = process.env[options.required] === '1';

  test.beforeAll(() => {
    if (options.gated && mustRun) {
      throw new Error(
        `${options.required}=1, но ${options.missing}: ${options.what} НЕ ПРОВЕРЕН. ` +
          'Пропуск здесь неотличим от успеха, поэтому это отказ, а не skip.',
      );
    }
  });

  test.skip(options.gated && !mustRun, `${options.missing} — сценарий не идёт`);
}

/**
 * Пропустить, потому что этот файл проверяет ПРОТИВОПОЛОЖНОЕ состояние.
 *
 * Не долг и не дыра: при поднятом соседе верен соседний файл, при
 * неподнятом — этот. Обязательным такой пропуск не станет никогда,
 * поэтому у него нет переменной «обязан» — и это записано здесь, а не
 * подразумевается.
 */
export function skipAsOtherScenario(when: boolean, why: string): void {
  test.skip(when, `другой сценарий: ${why}`);
}
