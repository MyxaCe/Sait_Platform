import { NextResponse } from 'next/server';
import { accessNotice, getTenantAccess } from '@/lib/tenant';

/**
 * Состояние границы доступа тенанта, посчитанное В РАНТАЙМЕ (WEB-07).
 *
 * **Зачем ручка.** Вопрос к границе задаёт общий макет витрины — строка
 * тикера стоит на всех 156 страницах. Любой рантаймовый вопрос из макета
 * увёл бы в динамику всю витрину, а она остаётся редакционной границей
 * (Р-030, п. 2). Поэтому макет границу не спрашивает: спрашивает
 * островок в браузере, а отвечает эта ручка — она динамическая по
 * построению и читает окружение контейнера, а не окружение сборки.
 *
 * **Что отдаётся и чего не отдаётся.** Состояние, причина и список
 * разрешённых символов — всё это и так видно на странице. Ничего из
 * конфигурации тенанта, кроме самого allow-list, сюда не попадает:
 * ручка не место утечки (тот же критерий, что у отпечатка в
 * `/api/health`).
 *
 * `Set` в JSON не сериализуется — символы уезжают массивом, и это
 * граница формата, а не изменение решения: решение осталось в
 * `@broker/tenant`.
 */
export const dynamic = 'force-dynamic';

export async function GET() {
  const access = await getTenantAccess();
  const notice = accessNotice(access);

  return NextResponse.json(
    {
      state: access.state,
      reason: access.state === 'unavailable' ? access.reason : undefined,
      symbols: access.state === 'allowed' ? [...access.symbols] : [],
      notice,
    },
    // Ответ про рантайм-состояние не имеет права осесть ни в одном кеше
    // по дороге: замороженный диагноз — ровно тот дефект, который чиним.
    { headers: { 'Cache-Control': 'no-store' } },
  );
}
