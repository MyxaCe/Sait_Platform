import { NextResponse } from 'next/server';
import { getMdsCatalog } from '@/lib/mds';

/**
 * Каталог стримящихся символов, посчитанный В РАНТАЙМЕ (WEB-08, Р-050).
 *
 * **Зачем ручка.** Строка тикера стоит в общем макете витрины, то есть на
 * всех её страницах, и макет рендерится на сборке. `MDS_HTTP_URL` —
 * рантаймовая переменная: на сборке её нет, каталог не читался, и
 * макет подставлял зашитый список символов. Выдуманные символы
 * оказывались в строке рядом с живыми ценами.
 *
 * Спросить каталог рантайм-вызовом прямо из макета нельзя — это увело бы
 * в динамику всю витрину, а она остаётся редакционной границей
 * (Р-030, п. 2). Поэтому ровно та же схема, что у границы доступа
 * (WEB-07): вопрос задаёт островок в браузере, отвечает эта ручка, и
 * окружение она читает своё — окружение контейнера, а не сборки.
 *
 * **Умолчания нет ни в одной ветке.** Каталога нет — так и сказано, с
 * причиной. Ни одно состояние не отдаёт список, который не подтверждён
 * ответом MDS.
 *
 * **Что отдаётся.** Перечень символов и причина отказа. Адрес MDS,
 * таймауты и прочая конфигурация сюда не попадают: ручка не место
 * утечки (тот же критерий, что у отпечатка в `/api/health`).
 */
export const dynamic = 'force-dynamic';

export async function GET() {
  const catalog = await getMdsCatalog();

  return NextResponse.json(
    catalog.state === 'available'
      ? { state: 'available', symbols: [...catalog.symbols] }
      : { state: 'unavailable', reason: catalog.reason, symbols: [] },
    // Ответ про рантайм-состояние не имеет права осесть ни в одном кеше
    // по дороге: замороженный ответ — ровно тот дефект, который чиним.
    { headers: { 'Cache-Control': 'no-store' } },
  );
}
