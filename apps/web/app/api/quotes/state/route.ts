import { NextResponse } from 'next/server';
import { getMdsQuotesState } from '@/lib/mds';

/**
 * Состояние котировок, посчитанное В РАНТАЙМЕ (WEB-12, Р-074).
 *
 * **Зачем отдельная ручка, а не поле в каталоге.** Каталог отвечает на
 * вопрос «какие символы вообще стримятся», это редко меняющийся
 * справочник с окном переиспользования в 300 с. Здесь вопрос другой —
 * «что с ценой ПРЯМО СЕЙЧАС», и замороженный ответ на него был бы ровно
 * тем дефектом, против которого написан §5б. Один ответ на оба вопроса
 * пришлось бы кешировать по худшему из двух, то есть не кешировать
 * каталог, либо по лучшему — то есть врать про котировки.
 *
 * **Та же схема, что у границы доступа и каталога** (WEB-07, WEB-08):
 * `MDS_HTTP_URL` — рантаймовая переменная, а макет витрины рендерится на
 * сборке, где её нет. Спрашивать из статического сегмента нельзя, поэтому
 * вопрос задаёт островок в браузере, а отвечает эта ручка, читающая
 * окружение своего контейнера.
 *
 * **Умолчания нет ни в одной ветке.** Ответа нет — так и сказано, с
 * причиной по оси канала. Пустые списки при `available` означают
 * «источник ничего не сказал», а не «всё свежо» (§5г, требование 1), и
 * различать эти два состояния за источник мы не вправе.
 */
export const dynamic = 'force-dynamic';

export async function GET() {
  const outcome = await getMdsQuotesState();

  return NextResponse.json(
    outcome.state === 'available'
      ? {
          state: 'available',
          unavailable: outcome.quotes.unavailable,
          missing: outcome.quotes.missing,
        }
      : { state: 'unavailable', reason: outcome.reason, unavailable: [], missing: [] },
    // Состояние котировок не имеет права осесть ни в одном кеше по дороге.
    { headers: { 'Cache-Control': 'no-store' } },
  );
}
