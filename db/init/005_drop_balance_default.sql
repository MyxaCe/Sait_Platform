-- Снятие умолчания баланса (WEB-29, Р-040).
--
-- ВНИМАНИЕ: файлы `db/init` Postgres выполняет ТОЛЬКО при первом
-- создании базы. На уже работающем сервере этот файл НЕ ПРИМЕНИТСЯ сам —
-- миграционного механизма у базы сайта нет (у CMS свой, `payload
-- migrate`). Этот оператор надо выполнить на живой базе руками; это
-- зона `deploy`, и он написан так, чтобы выполняться безопасно и
-- повторно.
--
-- Зачем: `DEFAULT 1000000` выдавал десять тысяч долларов любому INSERT
-- без колонки `balance_cents`. Оба создателя строки передают сумму явно,
-- поэтому умолчание мертво — но оно молча отменяло бы отказ регистрации
-- при незаданной сумме тенанта (Р-040).
ALTER TABLE demo_accounts ALTER COLUMN balance_cents DROP DEFAULT;
