import os from 'node:os';

/**
 * Ограничение пула потоков для прогона проверок (WEB-37).
 *
 * **Что измерено.** Машина разработчика: 8 ядер. Turbo гонит 10
 * тестовых задач параллельно, и каждый vitest по умолчанию поднимает
 * свой пул примерно в `ядра − 1` потока. Итого около семидесяти
 * потоков на восьми ядрах — девятикратная перегрузка.
 *
 * Следствие не «медленно», а **недостоверно**: измеряемый промежуток
 * проверки включает очередь за процессором. Проверки, идущие в покое
 * 350–630 мс, под полной нагрузкой упирались в предел в 5 секунд и
 * краснели — каждый раз разные, в разных пакетах. Красный прогон
 * выходил примерно каждый четвёртый (`WEB-33`).
 *
 * **Перегрузка не покупала скорость, она её тратила.** С
 * ограничением: три чистых прогона подряд и **25–29 секунд против 35**
 * без него. Это не размен, а снятие потерь.
 *
 * **Почему не поднять общий предел времени.** Он остаётся сторожем
 * настоящей медленности; подняв его, мы спрятали бы стоимость, и
 * завтра медленным стало бы что-то настоящее — незаметно.
 *
 * **Почему здесь, а не флагом в команде.** Через `--` аргумент
 * достаётся всем задачам turbo, включая `typecheck` и `lint`, которые
 * его не понимают, — падают все. Проверено: 0 из 19.
 *
 * **Число выводится из ядер, а не вписано.** Делитель 4 исходит из
 * того, что параллельных пакетов у нас примерно вдвое больше, чем
 * ядер: на 8 ядрах выходит 2 потока на пакет, на 16 — четыре, на
 * двухъядерном раннере CI — один. Переопределяется переменной
 * `VITEST_MAX_THREADS`, если машина окажется непохожей.
 */
function maxThreads() {
  const override = Number(process.env.VITEST_MAX_THREADS);
  if (Number.isInteger(override) && override > 0) return override;

  const cores =
    typeof os.availableParallelism === 'function' ? os.availableParallelism() : os.cpus().length;

  return Math.max(1, Math.floor(cores / 4));
}

/** Готовый блок для `test.poolOptions` любого пакета. */
export const poolOptions = {
  threads: {
    maxThreads: maxThreads(),
    minThreads: 1,
  },
};
