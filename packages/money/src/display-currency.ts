/**
 * ВАЛЮТА ОТОБРАЖЕНИЯ РЕАЛЬНЫХ ДЕНЕГ (решение штаба 10.11).
 *
 * Реальный счёт в терминале ведётся в USD (центы), деньги клиента — USDT
 * TRC20 1:1. В базе валюта остаётся той, что пришла из терминала (`USD` у
 * начислений `promo_rewards`), а в интерфейсе клиента и оператора сумма
 * реального счёта — ВСЕГДА USDT: начисления, награды, кешбэк, призы, IB,
 * баланс и вывод. Демо-счёт остаётся в своей валюте (USD).
 *
 * Одна точка правды: экраны не пишут литерал `'USDT'`, а берут его отсюда.
 */
export const REAL_ACCOUNT_CURRENCY = 'USDT' as const;

/**
 * Код валюты для показа суммы реального счёта. Хранимое значение (`USD` из
 * терминала, `USDT` проекции, `null`) на показ не влияет — 1:1, одна валюта.
 */
export function realMoneyCurrency(_stored?: string | null): typeof REAL_ACCOUNT_CURRENCY {
  return REAL_ACCOUNT_CURRENCY;
}
