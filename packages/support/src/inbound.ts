import { inTransaction, rollback, type PoolLike, type Queryable } from '@broker/money';
import type { SupportSettings } from './settings';
import { createTicketTx, enqueueAckTx, insertAttachments, type AttachmentInput } from './tickets';
import {
  domainOf,
  normalizeEmail,
  normalizeMessageId,
  sanitizeSubject,
  stripQuotedReply,
  threadTokenFromAddress,
  ticketNumberFromSubject,
} from './text';

/**
 * Приём входящего письма (дизайн §3.6/3.6.1). Нормализованное письмо от
 * IMAP-воркера → правила → привязка к тикету → сообщение. Всё — в одной
 * транзакции; дедуп по Message-ID — уникальностью `inbound_mail.message_id`
 * (второе такое же письмо — «дубль», ничего не создаёт).
 *
 * Правила по порядку: дубль → своё письмо (петля) → автоответчик (RFC 3834) →
 * блок-лист → лимит писем с адреса → привязка:
 *   1) In-Reply-To/References на наш Message-ID или на письмо этого тикета;
 *   2) метка `[#номер]` в теме — ТОЛЬКО если отправитель = контакт тикета
 *      (иначе любой, угадавший номер, дописывал бы в чужую переписку);
 *   3) plus-адрес `support+<token>@` (если хостинг его поддерживает);
 *   иначе — новый тикет канала email.
 * Закрытый/спам тикет не дописывается — новый тикет (ссылка на старый номер
 * видна в теме).
 */

export interface InboundMail {
  messageId: string | null;
  inReplyTo: string | null;
  references: string[];
  from: { address: string; name: string | null };
  to: string[];
  subject: string | null;
  text: string;
  date: Date | null;
  /** Заголовки, по которым узнаём автоответчики. */
  autoSubmitted?: string | null;
  precedence?: string | null;
  autoReplyHeader?: boolean;
  listId?: string | null;
  mailbox: string;
  uid?: number | null;
  uidValidity?: number | null;
  rawObjectKey?: string | null;
  attachments?: AttachmentInput[];
  /** Хеш сырого письма — Message-ID для писем без него. */
  rawSha256?: string;
}

export type InboundVerdict =
  | { verdict: 'duplicate' }
  | { verdict: 'own' | 'loop' | 'blocked' | 'spam'; reason: string }
  | { verdict: 'accepted'; ticketId: string; number: number; created: boolean; messageId: string };

export interface InboundOptions {
  settings: SupportSettings;
  /** Адрес ящика поддержки (свои письма — петля). */
  ownAddresses: readonly string[];
  now?: Date;
}

function isAutoGenerated(m: InboundMail): string | null {
  const as = (m.autoSubmitted ?? '').trim().toLowerCase();
  if (as && as !== 'no') return `auto-submitted: ${as}`;
  const prec = (m.precedence ?? '').trim().toLowerCase();
  if (['bulk', 'junk', 'list', 'auto_reply'].includes(prec)) return `precedence: ${prec}`;
  if (m.autoReplyHeader) return 'x-autoreply';
  if (m.listId) return 'list-id';
  const local = normalizeEmail(m.from.address).split('@')[0] ?? '';
  if (/^(mailer-daemon|postmaster|no-?reply|do-?not-?reply|bounce[s]?)$/.test(local)) return `sender: ${local}`;
  return null;
}

async function findByThread(tx: Queryable, ids: readonly string[]): Promise<string | null> {
  if (ids.length === 0) return null;
  const r = await tx.query(
    `SELECT ticket_id FROM (
        SELECT ticket_id, 1 AS p FROM outbound_mail WHERE rfc_message_id = ANY($1::text[]) AND ticket_id IS NOT NULL
        UNION ALL
        SELECT ticket_id, 2 AS p FROM support_messages WHERE email_message_id = ANY($1::text[])
      ) x ORDER BY p LIMIT 1`,
    [ids],
  );
  return (r.rows[0]?.ticket_id as string | undefined) ?? null;
}

export async function processInboundMail(db: PoolLike, mail: InboundMail, opts: InboundOptions): Promise<InboundVerdict> {
  const now = opts.now ?? new Date();
  const from = normalizeEmail(mail.from.address);
  const messageId =
    normalizeMessageId(mail.messageId) ?? `<missing-${mail.rawSha256 ?? `${from}-${mail.date?.getTime() ?? now.getTime()}`}@inbound>`;
  const subject = sanitizeSubject(mail.subject ?? '') || '(без темы)';

  return inTransaction<InboundVerdict>(db, async (tx) => {
    const ins = await tx.query(
      `INSERT INTO inbound_mail (mailbox, uid, uidvalidity, message_id, from_address, to_addresses, subject, received_at,
         raw_object_key)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
       ON CONFLICT (message_id) DO NOTHING RETURNING id`,
      [
        mail.mailbox,
        mail.uid ?? null,
        mail.uidValidity ?? null,
        messageId,
        from,
        mail.to.map(normalizeEmail),
        subject,
        mail.date ?? now,
        mail.rawObjectKey ?? null,
      ],
    );
    if (!ins.rows[0]) return { verdict: 'duplicate' as const };
    const inboundId = String(ins.rows[0].id);

    const verdict = async (v: 'own' | 'loop' | 'blocked' | 'spam', reason: string) => {
      await tx.query(`UPDATE inbound_mail SET verdict = $2, verdict_reason = $3 WHERE id = $1`, [inboundId, v, reason]);
      return { verdict: v, reason } as const;
    };

    if (opts.ownAddresses.map(normalizeEmail).includes(from)) return verdict('own', 'письмо с адреса поддержки');
    const auto = isAutoGenerated(mail);
    if (auto) return verdict('loop', auto);
    const blocked = await tx.query(
      `SELECT 1 FROM support_blocklist
        WHERE (kind = 'email' AND lower(value) = $1) OR (kind = 'domain' AND lower(value) = $2) LIMIT 1`,
      [from, domainOf(from)],
    );
    if (blocked.rows.length > 0) return verdict('blocked', 'адрес в блок-листе');
    const recent = await tx.query(
      `SELECT count(*)::int AS n FROM inbound_mail
        WHERE lower(from_address) = $1 AND created_at > $2 AND verdict = 'accepted'`,
      [from, new Date(now.getTime() - 3_600_000)],
    );
    if (Number(recent.rows[0]?.n ?? 0) >= opts.settings.limits.emailsPerSenderPerHour) {
      return verdict('spam', `больше ${opts.settings.limits.emailsPerSenderPerHour} писем в час с адреса`);
    }

    // Привязка к тикету.
    const threadIds = [mail.inReplyTo, ...mail.references]
      .map((x) => normalizeMessageId(x))
      .filter((x): x is string => x !== null);
    let ticketId = await findByThread(tx, threadIds);
    if (!ticketId) {
      const n = ticketNumberFromSubject(mail.subject);
      if (n !== null) {
        const r = await tx.query(`SELECT id FROM support_tickets WHERE number = $1 AND lower(contact_email) = $2`, [n, from]);
        ticketId = (r.rows[0]?.id as string | undefined) ?? null;
      }
    }
    if (!ticketId) {
      const token = threadTokenFromAddress(mail.to, opts.ownAddresses[0] ?? '');
      if (token) {
        const r = await tx.query(`SELECT id FROM support_tickets WHERE email_thread_token = $1`, [token]);
        ticketId = (r.rows[0]?.id as string | undefined) ?? null;
      }
    }

    const body = stripQuotedReply(mail.text || '') || '(пустое письмо)';
    let existing: Record<string, unknown> | undefined;
    if (ticketId) {
      const r = await tx.query(
        `SELECT id, number, status, reply_channel FROM support_tickets WHERE id = $1 FOR UPDATE`,
        [ticketId],
      );
      existing = r.rows[0];
      if (existing && (existing.status === 'closed' || existing.status === 'spam')) existing = undefined;
    }

    let result: { ticketId: string; number: number; created: boolean; messageId: string };
    if (existing) {
      const m = await tx.query(
        `INSERT INTO support_messages (ticket_id, author_kind, channel, body_text, email_message_id, email_in_reply_to)
         VALUES ($1, 'client', 'email', $2, $3, $4) RETURNING id`,
        [existing.id, body, messageId, normalizeMessageId(mail.inReplyTo)],
      );
      await tx.query(
        `UPDATE support_tickets SET last_client_message_at = $2, updated_at = $2,
           status = CASE WHEN status IN ('waiting_client', 'resolved') THEN 'open' ELSE status END,
           resolved_at = CASE WHEN status = 'resolved' THEN NULL ELSE resolved_at END
         WHERE id = $1`,
        [existing.id, now],
      );
      result = { ticketId: String(existing.id), number: Number(existing.number), created: false, messageId: String(m.rows[0]!.id) };
    } else {
      const locale = /[а-яё]/i.test(`${subject} ${body}`) ? 'ru' : 'en';
      const c = await createTicketTx(tx, opts.settings, {
        userId: null,
        contactEmail: from,
        contactName: mail.from.name?.trim().slice(0, 120) || null,
        locale,
        origin: 'email',
        replyChannel: 'email',
        subject,
        body,
        createdAt: now,
        emailMessageId: messageId,
        emailInReplyTo: normalizeMessageId(mail.inReplyTo),
      });
      if (!c) return rollback({ verdict: 'duplicate' as const });
      await enqueueAckTx(tx, opts.settings, {
        ...c,
        to: from,
        subject,
        contactName: mail.from.name,
        locale,
        inReplyTo: messageId,
      });
      result = { ticketId: c.ticketId, number: c.number, created: true, messageId: c.messageId };
    }
    if (mail.attachments?.length) await insertAttachments(tx, result.ticketId, result.messageId, mail.attachments);
    await tx.query(
      `UPDATE inbound_mail SET verdict = 'accepted', ticket_id = $2, support_message_id = $3 WHERE id = $1`,
      [inboundId, result.ticketId, result.messageId],
    );
    return { verdict: 'accepted' as const, ...result };
  });
}

/** Письмо не разобралось — запись для оператора (сырое .eml в хранилище). */
export async function recordInboundFailure(
  db: Queryable,
  m: { mailbox: string; uid: number | null; uidValidity: number | null; messageId: string; from: string; subject: string | null; rawObjectKey: string | null; error: string },
): Promise<void> {
  await db.query(
    `INSERT INTO inbound_mail (mailbox, uid, uidvalidity, message_id, from_address, subject, verdict, verdict_reason, raw_object_key)
     VALUES ($1, $2, $3, $4, $5, $6, 'failed', $7, $8)
     ON CONFLICT (message_id) DO NOTHING`,
    [m.mailbox, m.uid, m.uidValidity, m.messageId, m.from || 'unknown', m.subject, m.error.slice(0, 500), m.rawObjectKey],
  );
}
