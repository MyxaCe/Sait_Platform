/**
 * Чтение переменной окружения: **пустая строка — это отсутствие**
 * (WEB-21, решение штаба).
 *
 * ## Зачем отдельная функция вместо `??`
 *
 * `process.env.X ?? 'умолчание'` отсекает `undefined` и **пропускает
 * пустую строку**. А пустая строка берётся сама собой: аргумент сборки,
 * объявленный с пустым значением, перекрывает умолчание из Dockerfile;
 * `X=` в `.env`; незаполненная подстановка в компоузе.
 *
 * Механизм двойной, и **обе половины безобидны поодиночке**. Поэтому
 * его и не видно: ни в компоузе, ни в коде по отдельности ошибки нет.
 *
 * ## Чем это кончилось на самом деле
 *
 * Первый же образ витрины уехал с **нерабочими кнопками входа**:
 * `NEXT_PUBLIC_CABINET_URL` был пустым, умолчание не сработало, в
 * `href` попала пустая строка — и ссылка на кабинет стала ссылкой на
 * саму витрину. Прогон был зелёным: он проверял доставку, а не
 * содержимое.
 *
 * ## Родня, названная штабом
 *
 * Это тот же класс, что «не всякая подстановка нуля ложь»: там ноль мог
 * быть настоящим значением, здесь пустая строка **проходит за
 * незаданное**. Разница в том, что пустая строка настоящим значением не
 * бывает никогда — переменная либо задана, либо нет.
 *
 * Пробелы по краям срезаются по той же причине: `X=" "` в файле
 * окружения — это опечатка, а не адрес.
 */
export function readEnv(raw: string | undefined | null): string | null {
  const trimmed = typeof raw === 'string' ? raw.trim() : '';
  return trimmed.length > 0 ? trimmed : null;
}

/**
 * Значение окружения либо умолчание. Замена `process.env.X ?? '…'`.
 *
 * Умолчание применяется и к пустой строке — в этом вся суть.
 */
export function envOr(raw: string | undefined | null, fallback: string): string {
  return readEnv(raw) ?? fallback;
}

/**
 * Имя окружения для трекера ошибок, когда его не назвали (WEB-32).
 */
export const UNKNOWN_ENVIRONMENT = 'unknown';

/**
 * Окружение для трекера ошибок.
 *
 * **Чем было плохо умолчание `'test'`.** Оно не пустая строка и не
 * ноль — оно хуже: это **осмысленное утверждение о том, чего мы не
 * знаем**. Ненастроенный прод отчитывался как тестовый контур, а
 * «тестовые» ошибки смотрят последними или не смотрят вовсе. Отказ
 * получал вид, по которому его не станут разбирать.
 *
 * Тот же класс, что справочная цена вместо котировки, только
 * пострадавший не посетитель, а дежурный: ему показывают обжитую
 * корзину вместо неизвестной.
 *
 * **Почему `'unknown'`, а не отказ инициализации.** Отказ лишил бы нас
 * сообщений об ошибках целиком — молча потерять их хуже, чем получить
 * с честной меткой. Значение здесь и есть сигнал: `unknown` в трекере
 * видит ровно тот, кому он нужен, и это вопрос, который задают сразу.
 *
 * **Почему без предупреждения в лог.** Оно стояло бы только там, где
 * мы и так печатаем строки запуска, то есть в двух местах из восьми.
 * Асимметричное предупреждение приживается хуже, чем значение, и
 * расходится с остальными при первой правке.
 */
export function sentryEnvironment(raw: string | undefined | null): string {
  return readEnv(raw) ?? UNKNOWN_ENVIRONMENT;
}
