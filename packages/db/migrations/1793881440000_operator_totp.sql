-- Двухфакторная аутентификация оператора — TOTP (ADM-13, Р-454 III-3).
-- Ратифицировано: второй фактор ОБЯЗАТЕЛЕН до боевой работы, и это именно
-- TOTP, а не SMS (SMS уязвим к SIM-swap). Фундамент (ADM-01) и пароль (пакет
-- C) завели вход по одному фактору; эта миграция добавляет носитель второго —
-- по образцу `1793535840000_operator_password_hash`: применённую миграцию не
-- переписывают, новое состояние схемы вводится новым файлом.
--
-- `totp_secret` — общий секрет TOTP в base32 (RFC 4648), тот же, что кодируется
-- в provisioning-URI (otpauth://) при регистрации. Колонка NULLABLE, и это НЕ
-- недосмотр, а состояние «2FA не настроена»: NULL = у оператора ещё нет второго
-- фактора. Так существующий суперадмин (заведён сидом без секрета) не ломается
-- на входе — пароль он проходит, а дальше принудительно ведётся на регистрацию
-- TOTP (мягкая обработка «с первого дня», без тихого обхода).
--
-- `totp_enrolled_at` — когда второй фактор был подтверждён верным кодом.
-- Секрет пишется в базу ТОЛЬКО после успешной проверки кода из приложения:
-- `totp_secret IS NOT NULL` означает «2FA включена и подтверждена», а не
-- «секрет сгенерирован, но не доказан». Непроверенный секрет в базу не
-- попадает (живёт в краткоживущем подписанном тикете до подтверждения).
--
-- Down намеренно нет — как и у соседних миграций зоны (выкат вперёд, WEB-31).

ALTER TABLE operators ADD COLUMN IF NOT EXISTS totp_secret TEXT;
ALTER TABLE operators ADD COLUMN IF NOT EXISTS totp_enrolled_at TIMESTAMPTZ;

COMMENT ON COLUMN operators.totp_secret IS
  'Секрет TOTP (base32, RFC 4648) второго фактора (Р-454 III-3). NULL = 2FA не настроена.';
COMMENT ON COLUMN operators.totp_enrolled_at IS
  'Момент подтверждения TOTP верным кодом. NULL, пока 2FA не включена.';
