-- Порядок перезаписи остатка: колонка под accountSeq (WEB-43, Р-441).
--
-- Свидетель остатков поймал расхождение в тринадцать копеек: два события о
-- балансе применились в пределах четырёх миллисекунд, и порядок записи
-- оказался обратен порядку журнала. Причина (Р-438): prefetch(16) и
-- обработчик, который не ожидается, — до шестнадцати проекций идут
-- ОДНОВРЕМЕННО, и остаток пишет та, чей UPDATE закончил последним. Слепой
-- `UPDATE ... WHERE user_id` — last-writer-wins: старое событие с остатком
-- 10 000.00 затирало свежее 9 999.87.
--
-- Лечит это не сортировка (КОНТРАКТЫ §5): номер последней записи журнала
-- счёта едет на проводе, и проекция остатка применяет событие ТОЛЬКО при
-- строго большем номере. Здесь — место, где потребитель этот номер хранит.
--
-- Колонка NULLABLE сознательно. NULL = «номер по этому счёту ещё не виден»:
-- на время выката (Р-277) терминал шлёт номер не на всех событиях, а событие
-- без номера упорядочить нечем — его применяют как раньше, не затирая уже
-- сохранённый номер (COALESCE в проекции). Guard начнёт кусаться, когда
-- терминал сошлёт номер на всех событиях (TRM-60); строгой (NOT NULL)
-- колонка станет тем же шагом, не раньше.
--
-- Down намеренно нет — как и у соседних миграций зоны (выкат вперёд, WEB-31).
-- Откат свёлся бы к `DROP COLUMN account_seq`, но колонка аддитивна и
-- ничего не ломает своим присутствием — снимать нечего.
ALTER TABLE demo_accounts ADD COLUMN IF NOT EXISTS account_seq BIGINT;
