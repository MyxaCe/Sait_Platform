-- KYC-документы клиента — операторская поверхность обзора и решения
-- (ADM-08, Р-451 п.4). Фундамент (1793449440000) завёл `client_verification`
-- как ПЕРВОКЛАССНОЕ состояние проверки (не флаг в `users`); здесь к нему
-- прикладывается то, ПО ЧЕМУ оператор решает — поданные документы.
--
-- Граница зоны проведена в схеме намеренно. Клиентская ЗАГРУЗКА документов
-- (сторона кабинета) — отдельная зона и отдельная задача; эта миграция НЕ
-- заводит поверхность приёма файлов. Документ здесь — это ССЫЛКА на хранилище
-- (`storage_key`) и метаданные (вид, тип, время подачи); оператор их только
-- ПРОСМАТРИВАЕТ и на их основании решает. Байты файла в базу не кладём —
-- хранилище объектов владеет файлом, база владеет ссылкой на него.
--
-- Состояний проверки НЕ добавляем: переиспользуем четыре из фундамента
-- (`unverified`/`pending`/`verified`/`rejected`). Решение оператора меняет
-- `client_verification.state` и журналируется той же транзакцией — смотри
-- `apps/admin/lib/kyc/`. Per-документного изменяемого статуса здесь СОЗНАТЕЛЬНО
-- нет: решение принимается о клиенте целиком (Р-451 — субъект решения клиент),
-- а запись о подаче документа неизменяема по смыслу (её ставит сторона
-- кабинета, оператор не правит). Пятое состояние «запрошена переподача» —
-- изменение схемы, вынесено на ратификацию владельцу, здесь его нет.
--
-- Вид документа — закрытый CHECK по Р-451 п.4: паспорт/ID, селфи с liveness,
-- подтверждение адреса, источник средств. Неизвестный вид не пишется (fail-
-- closed): документ непонятного рода оператор не смог бы осмысленно оценить.
--
-- Down намеренно нет — как и у соседних миграций зоны (выкат вперёд, WEB-31).

CREATE TABLE IF NOT EXISTS kyc_documents (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES users(id),
  -- Вид документа по Р-451 п.4 (закрытый перечень, fail-closed).
  doc_kind TEXT NOT NULL CHECK (
    doc_kind IN ('identity', 'selfie_liveness', 'address_proof', 'source_of_funds')
  ),
  -- Ссылка на объект в хранилище (не байты). Чем ссылка адресуется (бакет,
  -- ключ) — забота стороны загрузки; операторская сторона трактует её как
  -- непрозрачный идентификатор для выдачи ссылки на просмотр.
  storage_key TEXT NOT NULL,
  -- MIME поданного файла — метаданные для подписи иконки/ссылки, опционально.
  content_type TEXT,
  -- Когда документ подан (сторона кабинета). Оператор видит свежесть — Р-451
  -- п.4 требует подтверждение адреса ≤3 мес; срок считается от этого времени.
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Карточка клиента собирает его документы — ходим по user_id.
CREATE INDEX IF NOT EXISTS kyc_documents_user_idx ON kyc_documents (user_id);

COMMENT ON TABLE kyc_documents IS
  'KYC-документы клиента для операторского обзора (ADM-08, Р-451 п.4). Ссылки на хранилище, не байты; загрузка — сторона кабинета.';
