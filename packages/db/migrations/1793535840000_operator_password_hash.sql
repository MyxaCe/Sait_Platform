-- Пароль оператора (ADM-01, пакет C, Р-451). Фундамент завёл таблицу
-- `operators` БЕЗ пароля — вход тогда ещё не строился. Пакет C добавляет
-- хеш пароля, и это отдельная миграция, а не правка прежней: применённую
-- миграцию не переписывают (механизм сверяет порядок, check-order), новое
-- состояние схемы вводится новым файлом.
--
-- `password_hash` — argon2id в PHC-строке (`$argon2id$v=19$m=…,t=…,p=…$…`):
-- алгоритм и параметры хранятся РЯДОМ с хешем (Р-451), чтобы вход мог
-- увидеть устаревшие параметры и прозрачно перехешировать.
--
-- Колонка NULLABLE, и это НЕ недосмотр, а fail-closed (Р-394): NULL = «входа
-- нет». Оператор, заведённый провижинингом без пароля, не может войти, пока
-- пароль не назначен, — и это тихий отказ, а не пустой пароль, который
-- прошёл бы за совпадение. Проверка входа требует непустой хеш И успешную
-- сверку argon2 — NULL не сверяется ни с чем.
--
-- Down намеренно нет — как и у соседних миграций зоны (выкат вперёд, WEB-31).

ALTER TABLE operators ADD COLUMN IF NOT EXISTS password_hash TEXT;

COMMENT ON COLUMN operators.password_hash IS
  'argon2id PHC-строка (Р-451). NULL = входа нет (fail-closed, Р-394).';
