/**
 * Слаг тенанта: кого именно обслуживает этот экземпляр (WEB-11).
 *
 * **Зачем отдельная функция ради одной строки.** Потому что строка была
 * написана шесть раз, и во всех шести одинаково неправильно:
 *
 * ```ts
 * process.env.SITE_SLUG ?? 'apex-ru'
 * ```
 *
 * `??` отсекает `undefined` и `null`, но **не пустую строку**. А пустая
 * строка — обычное состояние окружения: `SITE_SLUG=` в `.env`,
 * незаполненная подстановка в компоузе, переменная, затёртая пробелом.
 * В этом состоянии витрина уходила в CMS с `?site=`, CMS брала **сайт по
 * умолчанию**, и наружу это выходило не ошибкой, а **чужим тенантом**:
 * чужой бренд, чужой allow-list инструментов, чужая юрисдикция.
 *
 * Хуже всего не на витрине. Тот же `??` стоял в выдаче SSO-токенов
 * (`apps/cabinet/lib/sso/jwt.ts`) и в тенант-фильтре консюмера
 * (`apps/consumer/src/index.ts`): токен назвал бы чужого тенанта,
 * консюмер принял бы чужие события как свои. Ни то, ни другое не
 * оставляет следа в логах — всё выглядит штатно.
 *
 * Это ровно тот класс, который мы ловим четвёртый месяц: **пустое
 * значение, неотличимое от незаданного, подставляет правдоподобное
 * вместо отказа.** В отпечатке конфигурации пустая строка уже считается
 * «не задано» (`instance.ts`), и здесь обязано быть так же — иначе две
 * части системы расходятся в том, что считать заданным.
 *
 * **Почему всё-таки умолчание, а не отказ.** Отказ был бы честнее, и он
 * правильный ответ для регуляторной границы. Но смена «нет слага →
 * работаем как apex-ru» на «нет слага → не стартуем» меняет поведение
 * всех четырёх приложений разом, и это решение штаба, а не моё.
 * Здесь исправлено ровно одно: **пустая строка больше не выдаёт себя за
 * заданное значение.** Вопрос «должен ли незаданный слаг быть отказом»
 * вынесен в отчёт и НЕ закрыт этой функцией.
 */

/**
 * Тенант по умолчанию. Был зашит в шести местах одной и той же
 * строкой — теперь в одном, и виден поиском.
 */
export const DEFAULT_TENANT_SLUG = 'apex-ru';

/**
 * Слаг из окружения. Пустая строка и строка из пробелов — это «не
 * задано», а не слаг.
 *
 * Пробелы отсекаются по той же причине, по которой они отсекаются в
 * кодах юрисдикций: значение, отличающееся от нужного невидимым
 * символом, даёт отказ, причину которого не видно глазами.
 */
export function tenantSlug(raw: string | undefined | null): string {
  const trimmed = typeof raw === 'string' ? raw.trim() : '';
  return trimmed.length > 0 ? trimmed : DEFAULT_TENANT_SLUG;
}
