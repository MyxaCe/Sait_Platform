/**
 * Слаг тенанта: кого именно обслуживает этот экземпляр (WEB-11, PKG-05).
 *
 * ## Что здесь было и почему это оказалось тяжелее остальных умолчаний
 *
 * Строка `process.env.SITE_SLUG ?? 'apex-ru'` была написана шесть раз.
 * `??` отсекает `undefined`, но **не пустую строку**, а `SITE_SLUG=` в
 * `.env` и незаполненная подстановка в компоузе дают именно её. Наружу
 * это выходило не ошибкой, а **чужим тенантом**: CMS по пустому
 * `?site=` отдаёт сайт по умолчанию.
 *
 * Остальные умолчания платформы подставлялись в то, что **видно**: цену,
 * баланс, цвет. Это подставлялось **в личность** — в то, от чьего имени
 * мы действуем. Токен входа назвал бы чужого тенанта, тенант-фильтр
 * консюмера принял бы чужие события за свои. Ни то, ни другое не
 * оставляет следа ни на экране, ни в логе.
 *
 * ## Решение штаба (PKG-05): незаданный слаг — ОТКАЗ, а не умолчание
 *
 * Прежняя правка лечила половину: пустая строка перестала выдавать себя
 * за заданную, но подставлялось умолчание `apex-ru`. Довод штаба:
 * **приложение, не знающее, чьё оно, продолжает работать и подписывает
 * документы.** Отказ виден немедленно, подмена — нет.
 *
 * Цена названа и принята: запуск без настроенного слага невозможен.
 *
 * ## Где проходит граница: сборка не обязана знать тенанта, процесс обязан
 *
 * Образ у нас **один на много тенантов** — это не случайность, а то, как
 * устроен компоуз: публичные адреса приходят build-arg'ами, а `SITE_SLUG`
 * стоит в `environment`, то есть назначается при запуске. Значит:
 *
 *  - **на сборке** слага может не быть, и это законно. Страницы, которым
 *    нужен тенант, получают закрытую границу (`not-configured`) — тот же
 *    fail-closed, что при недоступной CMS. Не авария;
 *  - **у работающего процесса** слаг обязан быть. Гейт стоит на старте
 *    (`instrumentation.ts` у Next, проверка окружения у консюмера), а не
 *    в разборе страницы: отказ при старте виден сразу и целиком, отказ
 *    на странице — по одной странице и только тому, кто её открыл.
 *
 * Требовать слаг на сборке значило бы завести гейт, который невозможно
 * удовлетворить одним образом на две страны. **Гейт, который невозможно
 * удовлетворить, отключают** — это мы уже проходили.
 *
 * ## Релея здесь нет, и это решение, а не пропуск
 *
 * `apps/relay` понятия тенанта **не имеет вовсе**: он читает outbox и
 * публикует строки, а тенант лежит внутри события. Компоуз контура
 * `SITE_SLUG` ему не задаёт. Потребовать слаг у релея значило бы
 * остановить исправный сервис ради единообразия — и гейт снова стал бы
 * невыполнимым. Проверено поиском по `apps/relay/src`: ни `SITE_SLUG`,
 * ни `tenant`, ни `slug` там не встречаются.
 */

/**
 * Незаданный слаг. Отдельный класс, а не голый `Error`: вызывающий
 * обязан отличать «мы не знаем, чьи мы» от любой другой поломки —
 * например, в обработчике старта.
 */
export class MissingTenantSlugError extends Error {
  readonly code = 'missing-tenant-slug';

  constructor(where: string) {
    super(
      `SITE_SLUG не задан (${where}). Приложение не знает, какой тенант обслуживает, ` +
        'и не имеет права работать от чужого имени: прежнее умолчание «apex-ru» ' +
        'подставляло чужой бренд, чужой allow-list и чужую юрисдикцию, а в выдаче ' +
        'токена — чужого тенанта. Задайте SITE_SLUG в окружении процесса (PKG-05).',
    );
    this.name = 'MissingTenantSlugError';
  }
}

/**
 * Слаг, если он задан. `null` — не задан.
 *
 * Пустая строка и строка из пробелов — это «не задано», а не слаг.
 * Пробелы отсекаются по той же причине, что в кодах юрисдикций:
 * значение, отличающееся от нужного невидимым символом, даёт отказ,
 * причину которого не видно глазами.
 *
 * Возвращает `null`, а не бросает, **намеренно**: есть законный случай,
 * когда слага нет и это не авария, — сборка. Бросать умеет
 * `requireTenantSlug`, и вызывающий выбирает осознанно, какой из двух
 * ему нужен.
 */
export function readTenantSlug(raw: string | undefined | null): string | null {
  const trimmed = typeof raw === 'string' ? raw.trim() : '';
  return trimmed.length > 0 ? trimmed : null;
}

/**
 * Слаг там, где без него нельзя: выдача токена, фильтр событий, старт
 * процесса. Бросает `MissingTenantSlugError`.
 *
 * `where` попадает в сообщение: «SITE_SLUG не задан» без указания места
 * заставляет искать по всему репозиторию.
 */
export function requireTenantSlug(raw: string | undefined | null, where: string): string {
  const slug = readTenantSlug(raw);
  if (slug === null) throw new MissingTenantSlugError(where);
  return slug;
}

/**
 * Проверка на старте процесса: отказать громко и целиком.
 *
 * Возвращает слаг, чтобы вызывающий мог его залогировать — «какой
 * тенант мы обслуживаем» это первое, что хочется знать в логе запуска,
 * и по нему же различают два экземпляра на одной машине.
 */
export function assertTenantSlugAtStartup(where: string): string {
  return requireTenantSlug(process.env.SITE_SLUG, where);
}
