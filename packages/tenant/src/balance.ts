/**
 * Стартовый баланс демо-счёта из конфига тенанта.
 *
 * Поле живёт по правилу, ПРОТИВОПОЛОЖНОМУ прежнему, и это решение штаба
 * Р-040. Legacy подставляла миллион центов умолчанием; v2 сознательно его
 * не повторяет: `null` значит «не задан ни на сайте, ни выше по цепочке».
 *
 * **Кабинет обязан отказать, а не подставить своё число.** Открыть
 * демо-счёт на сумму, которую никто не назначал, хуже, чем не открыть:
 * клиент получит баланс, за который никто не отвечает, и разойдётся с
 * терминалом, читающим тот же конфиг. Умолчание здесь — утверждение о
 * том, чего мы не знаем, и оно сразу становится деньгами на счёте.
 *
 * Прежнее обоснование («демо-деньги — параметр удобства, умолчание
 * ничего не разрешает») записано тут намеренно: оно было отменено
 * штабом, а не забыто. Отличить отменённое от недоделанного можно только
 * по записанному намерению.
 *
 * Три исхода, и ни один не сводится к другому:
 *
 *   set         — источник назвал сумму. Открываем счёт на неё.
 *   unset       — источник явно сказал `null`: владелец сумму не
 *                 назначал. Чинится в CMS, одним полем карточки сайта.
 *   unavailable — конфиг тенанта получить не удалось либо в поле мусор.
 *                 Чинится совсем в другом месте, и потому обязано быть
 *                 отличимо от `unset` (Р-025, п. 2).
 */

/** Почему суммы нет. Намеренно не склеено с причинами границы доступа:
 *  у срока годности списка (`expired`) к стартовому балансу отношения
 *  нет, а общий союз заставил бы обрабатывать несуществующий случай. */
export type TenantStartBalanceUnavailableReason =
  /** `CMS_API_URL` не задан — в сеть не ходим, узнать неоткуда. */
  | 'not-configured'
  /** CMS ответила не-2xx. */
  | 'http-error'
  /** Соединение отклонено, таймаут, мусор вместо JSON. */
  | 'network'
  /** Ответ пришёл, но поля нет либо в нём не целое неотрицательное
   *  число. `"NaN"` разбирается успешно и превращается в ноль — ноль
   *  здесь это счёт без денег, то есть отказ, похожий на значение. */
  | 'malformed';

export type TenantStartBalance =
  | { readonly state: 'set'; readonly cents: number }
  | { readonly state: 'unset' }
  | { readonly state: 'unavailable'; readonly reason: TenantStartBalanceUnavailableReason };

export const START_BALANCE_UNAVAILABLE: Readonly<
  Record<TenantStartBalanceUnavailableReason, TenantStartBalance>
> = {
  'not-configured': { state: 'unavailable', reason: 'not-configured' },
  'http-error': { state: 'unavailable', reason: 'http-error' },
  network: { state: 'unavailable', reason: 'network' },
  malformed: { state: 'unavailable', reason: 'malformed' },
};

/**
 * Разбор поля `demoStartBalanceCents`. Чистая функция.
 *
 * Строгая проверка типа, а не `Number(raw)`: `Number(null)` даёт `0`, и
 * «не задан» молча превратился бы в «счёт на ноль». Разбор и приведение —
 * два разных барьера, и второй умеет портить то, что первый пропустил.
 *
 * Ноль — ДОПУСТИМАЯ назначенная сумма: `site-config.v1` объявляет поле
 * как `integer | null` с `minimum: 0`. Собственный контракт источника
 * надёжнее нашего пересказа, поэтому отсекаем отрицательное и дробное,
 * а не «подозрительно маленькое».
 */
export function readStartBalance(raw: unknown): TenantStartBalance {
  if (raw === null) return { state: 'unset' };
  if (typeof raw !== 'number' || !Number.isSafeInteger(raw) || raw < 0) {
    return START_BALANCE_UNAVAILABLE.malformed;
  }
  return { state: 'set', cents: raw };
}
