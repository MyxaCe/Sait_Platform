/**
 * Срок годности списка разрешённых инструментов — решение штаба Р-030.
 *
 * Правило: **срок приходит от источника, а не выбирается нами.** То же,
 * по которому порог свежести котировок задаёт MDS: потребитель,
 * выбравший срок сам, молча разойдётся с источником, и оба будут правы.
 * Истёкший список означает `unavailable`, то есть закрыто, — а не
 * «продолжаем по последнему известному» (КОНТРАКТЫ.md §4б: бессрочного
 * last-good здесь не будет).
 *
 * Две вещи, которые здесь легко перепутать, и путать их нельзя.
 *
 * **Первое: срок годности списка — не директива кеширования HTTP.**
 * `no-store` и `no-cache` говорят про переиспользование ОТВЕТА
 * посредником, а не про то, сколько времени действительны разрешения.
 * Прочитать одно как другое — это «индикатор горит от того, что он не
 * называет»: мы бы закрыли границу на основании заголовка, который про
 * другое. Поэтому положительный `max-age`/`s-maxage` и `Expires` мы
 * принимаем как срок (источник прямо назвал окно переиспользования),
 * а `no-store`, `no-cache` и `max-age=0` — как **молчание о сроке**.
 *
 * **Второе: срок — абсолютный момент, названный источником, а не
 * «сейчас плюс N».** Окно, отсчитанное от момента РАЗБОРА, обнуляется
 * каждый раз, когда ответ приходит из кеша данных Next, — и список не
 * истекает никогда. Поэтому якорь — заголовок `Date` ответа; без него
 * срок считается неназванным.
 *
 * **Чего здесь сегодня нет.** Ни один из двух источников срока не
 * называет: legacy на `/v1/cms/sites/{slug}` отдаёт `Cache-Control:
 * no-store`, v2 на доставке — `private, no-cache` с `ETag`; в
 * `site-config.v1` поля со сроком нет вовсе (проверено по схеме
 * контракта в репозитории CMS, не по описанию). То есть ветка `named`
 * существует и проверена, но на сегодняшних источниках не исполняется —
 * это названо вслух в отчёте штабу и в TD-015, чтобы «написано и не
 * вызывается» не стало открытием через полгода.
 */

import { UNAVAILABLE, type TenantAccess } from './access';

/**
 * Окно, в течение которого витрина переиспользует собранную страницу
 * (ISR, ADR-009). Это **редакционная** граница: она решает, что
 * показать. Торговая граница — у терминала, он читает конфиг живым и
 * fail-closed. Пятиминутное окно на витрине означает лишнюю страницу в
 * выдаче, а не разрешённую сделку (Р-030, п. 2).
 *
 * **Это НЕ срок годности списка.** Срок годности приходит от источника и
 * живёт в `TenantListExpiry`; эта константа — наш потолок, и когда
 * источник назовёт срок короче, закроет границу именно он.
 */
export const EDITORIAL_REUSE_WINDOW_SECONDS = 300;

/**
 * Что источник сказал о сроке годности списка.
 *
 * Два состояния, и второе — не «срок бесконечен», а «источник о сроке
 * промолчал». Разница та же, что между пустым списком и отсутствующим
 * полем: умолчание — утверждение о том, чего мы не знаем.
 */
export type TenantListExpiry =
  /** Источник назвал момент, после которого списку верить нельзя. */
  | { readonly state: 'named'; readonly expiresAt: number }
  /** Источник срока не назвал. Действует наше редакционное окно, и это
   *  открытый пункт Р-030, а не закрытый (TD-015). */
  | { readonly state: 'unnamed' };

const UNNAMED: TenantListExpiry = { state: 'unnamed' };

/** Заголовки ответа. Минимум, который нужен, — чтобы тест не поднимал fetch. */
export interface ExpiryHeaders {
  get(name: string): string | null;
}

/** `max-age` / `s-maxage` из `Cache-Control`. `null` — директивы нет. */
function freshnessSeconds(cacheControl: string): number | null {
  // `s-maxage` адресован общим кешам и, когда он есть, перекрывает
  // `max-age` — наш ISR-слой это именно общий кеш.
  for (const directive of ['s-maxage', 'max-age']) {
    // Значение обязано кончаться концом строки или запятой: `max-age=1e999`
    // это не «1 секунда с хвостом», а мусор. Разбор и приведение — разные
    // барьеры, и второй умеет портить то, что первый пропустил.
    const match = new RegExp(`(?:^|,)\\s*${directive}\\s*=\\s*"?(\\d+)"?\\s*(?=,|$)`, 'i').exec(
      cacheControl,
    );
    if (match) {
      const seconds = Number(match[1]);
      return Number.isSafeInteger(seconds) ? seconds : null;
    }
  }
  return null;
}

/**
 * Срок годности, названный источником в заголовках ответа.
 *
 * Порядок как в HTTP: `s-maxage` → `max-age` → `Expires`. Нулевое и
 * отрицательное окно, `no-store` и `no-cache` — это молчание о сроке, а
 * не нулевой срок: см. шапку файла.
 */
export function readListExpiry(headers: ExpiryHeaders): TenantListExpiry {
  const originTime = Date.parse(headers.get('date') ?? '');
  const cacheControl = headers.get('cache-control') ?? '';
  const seconds = freshnessSeconds(cacheControl);

  if (seconds !== null && seconds > 0) {
    // Без `Date` окно не к чему привязать: отсчёт от «сейчас» обнулялся бы
    // при каждом чтении из кеша, и список не истекал бы никогда.
    if (!Number.isFinite(originTime)) return UNNAMED;
    return { state: 'named', expiresAt: originTime + seconds * 1000 };
  }

  const expires = Date.parse(headers.get('expires') ?? '');
  // `Expires` в прошлом — такая же директива «не переиспользовать», как
  // `no-cache`, и про срок действия разрешений она не говорит ничего.
  if (Number.isFinite(expires) && (!Number.isFinite(originTime) || expires > originTime)) {
    return { state: 'named', expiresAt: expires };
  }

  return UNNAMED;
}

/**
 * Применить срок годности к решению границы.
 *
 * Истёкший список закрывает границу с собственной причиной: сеть цела и
 * CMS жива, непригоден именно возраст разрешений. Называть это `network`
 * значило бы отправить дежурного чинить исправное.
 *
 * `unavailable` уже закрыт — срок к нему не применяется: у состояния
 * «списка нет» нет возраста.
 */
export function applyListExpiry(
  access: TenantAccess,
  expiry: TenantListExpiry,
  nowMs: number,
): TenantAccess {
  if (access.state === 'unavailable') return access;
  if (expiry.state === 'unnamed') return access;
  return nowMs > expiry.expiresAt ? UNAVAILABLE.expired : access;
}
