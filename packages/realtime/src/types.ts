/**
 * Состояние фида. `simulated` — данные не настоящие: цены синтезированы, к
 * рынку отношения не имеют. Это НЕ подвид `connected`: подключённость и
 * подлинность — разные вопросы, и их склейка породила B-018 (мок рапортовал
 * `connected`, индикатор горел «Данные в реальном времени» над случайным
 * блужданием). Подлинность решает RealtimeService по наличию адреса источника,
 * драйвера об этом не спрашивают — самоназвание драйвера подделывается даром.
 */
export type ConnStatus = 'connecting' | 'connected' | 'reconnecting' | 'offline' | 'simulated';

/**
 * Перечень категорий — ОДИН, и тип выводится из него (WEB-35).
 *
 * Разбору с провода нужен список во время выполнения: проверить, что
 * приехавшая категория из согласованных. Объявить его рядом с типом
 * значило бы завести две строки, независимо перечисляющие одно, — они
 * разойдутся при первой же новой категории, причём молча: тип не знает
 * о списке, список не знает о типе.
 */
export const INSTRUMENT_CATEGORIES = [
  'forex',
  'metals',
  'crypto',
  'indices',
  'stocks',
  'energy',
] as const;

export type InstrumentCategory = (typeof INSTRUMENT_CATEGORIES)[number];

export interface Quote {
  symbol: string;
  name: string;
  category: InstrumentCategory;
  /** Текущая цена (mid) */
  price: number;
  /** Знаков после запятой для отображения */
  digits: number;
  /**
   * Изменение от открытия дня, %.
   *
   * `null` — «цена известна, изменение — нет» (КОНТРАКТЫ.md, Р-118). Это
   * третье состояние, а не «нет котировки»: цена выше в этой же структуре
   * настоящая. Подставлять вместо него ноль запрещено — ноль это
   * утверждение «цена не изменилась», и отличить его от «не знаем»
   * потребитель уже не сможет.
   */
  changePercent: number | null;
  /**
   * Лучшая цена покупки и лучшая цена продажи (WEB-36).
   *
   * **Обнуляемые, а не необязательные, и это решение штаба.** Один
   * поставщик их даёт, второй не даёт вовсе. Необязательность
   * заставила бы выбирать между «выбросить все тики второго» и
   * «подставить выдуманное»; обнуляемость позволяет сказать «этих цен
   * нет» и остаться с настоящей ценой.
   *
   * **Ноль здесь не значение.** Нулевая цена покупки означала бы
   * сделку по нулю — это утверждение, а не отсутствие. Пусто — `null`.
   *
   * До WEB-36 обе цены приходили с биржи и **выбрасывались при
   * разборе**: кадр несёт 23 ключа, разборщик соседа объявлял 5. То
   * есть «нам их не дают» было неотличимо от «нам их дают, а мы
   * теряем» — ровно то третье следствие, ради которого писался
   * `parse-quote-batch`.
   */
  bid: number | null;
  ask: number | null;
  /** Unix ms последнего обновления; 0 — статичный начальный снапшот */
  ts: number;
}

/**
 * Транспорт фида. Реализации: socket.io (боевой) и мок (random walk).
 * Контракт одинаковый, поэтому замена мока на реальный фид — смена URL.
 */
export interface FeedDriver {
  connect(onBatch: (batch: Quote[]) => void, onStatus: (s: ConnStatus) => void): void;
  subscribe(symbols: string[]): void;
  unsubscribe(symbols: string[]): void;
  disconnect(): void;
}
